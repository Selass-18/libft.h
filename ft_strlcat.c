#include "libft.h"

size_t	ft_strlcat(char *dst, const char *src, size_t size)
{
	size_t	dlen;
	size_t	slen;
	size_t	i;
	size_t	j;

	dlen = 0;
	while (dlen < size && dst[dlen] != '\0')
		dlen++;
	slen = ft_strlen(src);
	if (size <= dlen)
		return (size + slen);
	i = dlen;
	j = 0;
	while (src[j] != '\0' && i < size - 1)
	{
		dst[i] = src[j];
		i++;
		j++;
	}
	dst[i] = '\0';
	return (dlen + slen);
}
